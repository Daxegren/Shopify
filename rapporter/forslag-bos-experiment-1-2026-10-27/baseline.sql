       COUNT(DISTINCT url) AS antal_url, SUM(clicks) AS klick, SUM(impressions) AS visningar
FROM `gorilla-sports-data.site_audit.gsc_combined_bestofsports_se`
WHERE data_date BETWEEN START AND SLUT;

